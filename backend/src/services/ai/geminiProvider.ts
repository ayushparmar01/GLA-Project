import { IAiProvider, AiGenerateOptions, AiProviderResponse } from './aiProvider.interface.js';

export class GeminiProvider implements IAiProvider {
  public readonly providerName = 'GEMINI';
  private apiKey: string;
  private model: string;
  private defaultTimeoutMs: number;

  constructor(apiKey: string, model: string = 'gemini-1.5-flash', defaultTimeoutMs: number = 15000) {
    this.apiKey = apiKey.trim();
    this.model = model.trim();
    this.defaultTimeoutMs = defaultTimeoutMs;
  }

  public isConfigured(): boolean {
    return Boolean(this.apiKey && this.apiKey.length >= 10);
  }

  public async generateText(
    prompt: string,
    options?: AiGenerateOptions
  ): Promise<AiProviderResponse> {
    if (!this.isConfigured()) {
      throw new Error('Gemini API key is not configured.');
    }

    const timeout = options?.timeoutMs || this.defaultTimeoutMs;
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), timeout);

    const url = `https://generativelanguage.googleapis.com/v1beta/models/${encodeURIComponent(
      this.model
    )}:generateContent?key=${encodeURIComponent(this.apiKey)}`;

    const systemInstruction = options?.systemPrompt
      ? { parts: [{ text: options.systemPrompt }] }
      : undefined;

    const requestBody = {
      contents: [{ role: 'user', parts: [{ text: prompt }] }],
      systemInstruction,
      generationConfig: {
        temperature: options?.temperature ?? 0.7,
        maxOutputTokens: options?.maxTokens ?? 1024,
      },
    };

    try {
      const response = await fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(requestBody),
        signal: controller.signal,
      });

      clearTimeout(timeoutId);

      if (!response.ok) {
        const errorText = await response.text();
        throw new Error(`Gemini API HTTP ${response.status}: ${errorText.substring(0, 200)}`);
      }

      const data = await response.json();
      const content =
        data.candidates?.[0]?.content?.parts?.[0]?.text || 'No response generated by Gemini model.';
      const tokensUsed = data.usageMetadata?.totalTokenCount || 0;

      return {
        content,
        isFallback: false,
        provider: this.providerName,
        tokensUsed,
      };
    } catch (error: any) {
      clearTimeout(timeoutId);
      if (error.name === 'AbortError') {
        throw new Error(`Gemini API call timed out after ${timeout}ms`);
      }
      throw error;
    }
  }

  public async generateStructured<T>(
    prompt: string,
    options?: AiGenerateOptions
  ): Promise<{ data: T; isFallback: boolean; provider: string; fallbackReason?: string }> {
    const jsonPrompt = `${prompt}\n\nIMPORTANT: Respond with ONLY a valid, raw JSON object matching the requested structure. Do not include markdown codeblocks or extra text.`;
    const response = await this.generateText(jsonPrompt, {
      ...options,
      temperature: 0.2, // Low temperature for deterministic JSON output
    });

    try {
      let raw = response.content.trim();
      // Clean possible markdown code fences if model output ```json ... ```
      if (raw.startsWith('```json')) {
        raw = raw.replace(/^```json\s*/, '').replace(/\s*```$/, '');
      } else if (raw.startsWith('```')) {
        raw = raw.replace(/^```\s*/, '').replace(/\s*```$/, '');
      }

      const parsed = JSON.parse(raw);
      return {
        data: parsed as T,
        isFallback: false,
        provider: this.providerName,
      };
    } catch (parseError) {
      throw new Error(`Failed to parse structured JSON from Gemini response: ${(parseError as Error).message}`);
    }
  }
}
