import { IAiProvider, AiGenerateOptions, AiProviderResponse } from './aiProvider.interface.js';

export class OpenAiProvider implements IAiProvider {
  public readonly providerName = 'OPENAI';
  private apiKey: string;
  private model: string;
  private defaultTimeoutMs: number;

  constructor(apiKey: string, model: string = 'gpt-4o-mini', defaultTimeoutMs: number = 15000) {
    this.apiKey = apiKey.trim();
    this.model = model.trim();
    this.defaultTimeoutMs = defaultTimeoutMs;
  }

  public isConfigured(): boolean {
    return Boolean(this.apiKey && this.apiKey.length >= 10);
  }

  public async generateText(
    prompt: string,
    options?: AiGenerateOptions
  ): Promise<AiProviderResponse> {
    if (!this.isConfigured()) {
      throw new Error('OpenAI API key is not configured.');
    }

    const timeout = options?.timeoutMs || this.defaultTimeoutMs;
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), timeout);

    const messages = [];
    if (options?.systemPrompt) {
      messages.push({ role: 'system', content: options.systemPrompt });
    }
    messages.push({ role: 'user', content: prompt });

    const requestBody = {
      model: this.model,
      messages,
      temperature: options?.temperature ?? 0.7,
      max_tokens: options?.maxTokens ?? 1024,
    };

    try {
      const response = await fetch('https://api.openai.com/v1/chat/completions', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${this.apiKey}`,
        },
        body: JSON.stringify(requestBody),
        signal: controller.signal,
      });

      clearTimeout(timeoutId);

      if (!response.ok) {
        const errorText = await response.text();
        throw new Error(`OpenAI API HTTP ${response.status}: ${errorText.substring(0, 200)}`);
      }

      const data = await response.json();
      const content =
        data.choices?.[0]?.message?.content || 'No response generated by OpenAI model.';
      const tokensUsed = data.usage?.total_tokens || 0;

      return {
        content,
        isFallback: false,
        provider: this.providerName,
        tokensUsed,
      };
    } catch (error: any) {
      clearTimeout(timeoutId);
      if (error.name === 'AbortError') {
        throw new Error(`OpenAI API call timed out after ${timeout}ms`);
      }
      throw error;
    }
  }

  public async generateStructured<T>(
    prompt: string,
    options?: AiGenerateOptions
  ): Promise<{ data: T; isFallback: boolean; provider: string; fallbackReason?: string }> {
    const jsonPrompt = `${prompt}\n\nRespond with ONLY valid, raw JSON matching the required schema.`;
    const response = await this.generateText(jsonPrompt, {
      ...options,
      temperature: 0.2,
    });

    try {
      let raw = response.content.trim();
      if (raw.startsWith('```json')) {
        raw = raw.replace(/^```json\s*/, '').replace(/\s*```$/, '');
      } else if (raw.startsWith('```')) {
        raw = raw.replace(/^```\s*/, '').replace(/\s*```$/, '');
      }

      const parsed = JSON.parse(raw);
      return {
        data: parsed as T,
        isFallback: false,
        provider: this.providerName,
      };
    } catch (parseError) {
      throw new Error(`Failed to parse structured JSON from OpenAI response: ${(parseError as Error).message}`);
    }
  }
}
